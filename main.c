#include <stdio.h>  // ввод-вывод (чтобы работали printf и scanf)
#include <stdlib.h> // для системных функций (очистка экрана или смена кодировки)

#define MAX_SIZE 100 // жесткое правило: максимальный размер массива — 100 элементов
                     // если хотим поменять размер,то меняем число в этой строчке 
// предупреждаем компьютер, какие функции мы сами написали ниже, чтобы он не ругался при их вызове в main.
void inputArray(int array[], int size);
void printArray(const int array[], int size);
int findMin(const int array[], int size);
int findMax(const int array[], int size);
long long calculateSum(const int array[], int size);
double calculateAverage(const int array[], int size);
void performIndividualTask(const int array[], int size); // (Вариант 6)
int main(void)
{
    // этот кусочек нужен только для Windows
    #ifdef _WIN32
        system("chcp 65001 > nul"); // включаем кодировку UTF-8
    #endif

    int array[MAX_SIZE]; // выделяем в памяти место под массив, где может храниться до 100 чисел.
    int size;            // переменная, куда мы запишем реальный размер массива, который введет пользователь.

    // просим пользователя ввести размер
    printf("Введите размер массива от 1 до %d: ", MAX_SIZE);
    
    // считываем число. И тут же делаем СВЕРХВАЖНУЮ проверку валидацию (процесс проверки и подтверждения того, что процесс или данные реально удовлетворяют потребности и решают поставленные перед ними задачи)
    if (scanf("%d", &size) != 1 || size < 1 || size > MAX_SIZE)
    {
        // если ввели буквы вместо цифр, или число меньше 1, или больше 100 — закрываем программу.
        printf("Ошибка: недопустимый размер массива.\n");
        return 1; // 1 означает, что программа завершилась с ошибкой.
    }

    inputArray(array, size); // вызываем функцию, чтобы заполнить массив числами с клавиатуры.
    
    printf("\nИсходный массив:\n");
    printArray(array, size); // вызываем функцию, которая просто напечатает наш массив в строчку.
    /* тут мы вызываем функции расчетов и сохраняем результаты в переменные */
    int minIdx = findMin(array, size); // индекс минимального числа
    int maxIdx = findMax(array, size); // индекс максимального числа
    long long sum = calculateSum(array, size); // считаем сумму (long long нужен, чтобы число поместилось, если сумма будет огромной)
    double avg = calculateAverage(array, size); // считаем среднее (double — значит дробное число)

    // выводим всё это на экран
    printf("\n--- Основные характеристики ---\n");
    printf("Минимальный элемент: %d (индекс: %d)\n", array[minIdx], minIdx);
    printf("Максимальный элемент: %d (индекс: %d)\n", array[maxIdx], maxIdx);
    printf("Сумма элементов: %lld\n", sum);
    printf("Среднее арифметическое: %.2f\n", avg); // .2f означает "округлить до 2 знаков после запятой"
    // заводим три счетчика для знаков чисел и изначально обнуляем их
    int pos = 0, neg = 0, zeros = 0;
    
    //цикол по всему массиву от 0 до конца (size)
    for (int i = 0; i < size; i++) {
        if (array[i] > 0) pos++;      // если число больше нуля —  + счетчик положительных
        else if (array[i] < 0) neg++; // если меньше — + счетчик отрицательных
        else zeros++;                 // если это ноль — + счетчик нулей
    }
    printf("Количество: положительных = %d, отрицательных = %d, нулей = %d\n", pos, neg, zeros);

    // счетчики для чётных и нечётных чисел
    int even = 0, odd = 0;
    for (int i = 0; i < size; i++) {
        // проверка остатка от деления на 2, если он равен 0 — число чётное.
        if (array[i] % 2 == 0) even++;
        else odd++;
    }
    printf("Количество: чётных = %d, нечётных = %d\n", even, odd);
    int a, b; // пПеременные для левой и правой границы диапазона
    printf("\nВведите границы диапазона [a, b] через пробел: ");
    
    // если пользователь успешно ввел два числа:
    if (scanf("%d %d", &a, &b) == 2) {
        printf("Элементы в диапазоне [%d, %d]: ", a, b);
        int found = 0; // переменная-флаг. 0 — значит пока ничего не нашли.
        
        for (int i = 0; i < size; i++) {
            // если текущее число больше или равно 'a' И одновременно меньше или равно 'b'
            if (array[i] >= a && array[i] <= b) {
                printf("%d ", array[i]); // выводим его на экран
                found = 1; // меняем флаг на 1 
            }
        }
        if (!found) printf("нет таких элементов"); // если прошли весь массив и флаг остался 0 — пишем, что ничего нет.
        printf("\n");
    }

    /* вызываем индивидуальное задание (вариант 6) */
    performIndividualTask(array, size);

    return 0; // конец главной функции. 0 означает, что всё прошло 
}
void inputArray(int array[], int size)
{
    printf("Введите %d элементов массива:\n", size);
    for (int i = 0; i < size; i++)
    {
        // пытаемся считать число. если пользователь ввел букву вместо цифры — scanf вернет НЕ 1.
        while (scanf("%d", &array[i]) != 1)
        {
            printf("Ошибочный ввод. Повторите ввод для элемента [%d]: ", i);
            while (getchar() != '\n'); // стираем эту ошибочную букву, чтобы программа не зависла в бесконечном цикле
        }
    }
}
void printArray(const int array[], int size)
{
    for (int i = 0; i < size; i++)
    {
        printf("%d ", array[i]); // печатаем каждое число через пробел
    }
    printf("\n"); // в конце переносим курсор на новую строку
}
long long calculateSum(const int array[], int size)
{
    long long sum = 0; // изначально сумма равна нулю
    for (int i = 0; i < size; i++)
    {
        sum += array[i]; // прибавляем каждое число из массива к общей сумме
    }
    return sum;
}

double calculateAverage(const int array[], int size)
{
    if (size == 0) return 0.0; // защита от деления на ноль
    
    // double перед суммой нужнен, чтобы заставить компьютер считать деление дробным, а не округлять его до целого!
    return (double)calculateSum(array, size) / size; // берем сумму и делим на количество элементов
}
void performIndividualTask(const int array[], int size)
{
    printf("\n--- Индивидуальное задание (Вариант 6) ---\n");
    if (size <= 0) {
        printf("Длина возрастающего фрагмента: 0\n");
        return;
    }

    int maxLength = 1;    // переменная для хранения самой большой длины, которую мы найдем
    int currentLength = 1; // переменная для текущей длины 

    // начинаем со второго элемента (индекс 1) и сравниваем его с предыдущим
    for (int i = 1; i < size; i++)
    {
        // если текущее число больше предыдущего значит, мы растем
        if (array[i] > array[i - 1])
        {
            currentLength++; // увеличиваем длину текущего возрастающего ряда на 1
        }
        else // если число не больше рост прервался
        {
            // проверяем: наш текущий ряд побил прошлый рекорд maxLength
            if (currentLength > maxLength)
            {
                maxLength = currentLength; // если да — обновляем рекорд!
            }
            currentLength = 1; // сбрасываем текущую длину обратно в 1 (начинаем считать новый ряд заново)
        }
    }
    
    // финальная проверка после выхода из цикла (нужна на случай, если самый длинный ряд оказался в самом конце массива)
    if (currentLength > maxLength)
    {
        maxLength = currentLength;
    }

    printf("Длина самого длинного непрерывного строго возрастающего фрагмента: %d\n", maxLength);
}
